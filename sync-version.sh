#!/usr/bin/env bash
# Copies the version from src/common.h (OUTPOST_VERSION) into the exe's version resource, manifest and
# installer, and lists the game templates as resources, so everything always agrees.
set -euo pipefail
cd "$(dirname "$0")"
VER=$(grep -oP 'OUTPOST_VERSION L"\K[^"]+' src/common.h)
NUM=${VER%%-*}
IFS=. read -r MA MI PA <<< "$NUM"
MA=${MA:-0}; MI=${MI:-0}; PA=${PA:-0}
sed -i -E "s/^( FILEVERSION ).*/\1$MA,$MI,$PA,0/; s/^( PRODUCTVERSION ).*/\1$MA,$MI,$PA,0/; s/(VALUE \"FileVersion\", )\"[^\"]*\"/\1\"$VER\"/; s/(VALUE \"ProductVersion\", )\"[^\"]*\"/\1\"$VER\"/" res/outpost.rc
sed -i -E "s/(<assemblyIdentity type=\"win32\" name=\"larosa023.Outpost\" version=\")[^\"]*\"/\1$MA.$MI.$PA.0\"/" res/outpost.manifest
[ -f installer/outpost.nsi ] && sed -i -E "s/^(!define VERSION ).*/\1\"$VER\"/" installer/outpost.nsi
# built-in game templates: RCDATA 300, 301, …
{
  echo "// generated by sync-version.sh from templates/*.json"
  i=300
  for f in $(ls templates/*.json | grep -v index.json | sort); do echo "$i RCDATA \"../$f\""; i=$((i+1)); done
} > res/templates.rc
echo "Version $VER stamped; $(grep -c RCDATA res/templates.rc) templates embedded"
